pub fn sys_set_priority(_prio: isize) -> isize {
    trace!(
        "kernel:pid[{}] sys_set_priority",
        current_task().unwrap().pid.0
    );
    if _prio <= 2 {
        return -1;
    }
    current_task()
        .unwrap()
        .inner_exclusive_access()
        .update_priority(_prio as usize);
    _prio
}
